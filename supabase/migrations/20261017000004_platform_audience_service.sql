CREATE TABLE IF NOT EXISTS public.automated_audience_accounts (
  user_id uuid PRIMARY KEY REFERENCES public.user_profiles(id) ON DELETE RESTRICT,
  account_key text NOT NULL UNIQUE,
  conversation_style text NOT NULL DEFAULT 'warm'
    CHECK (conversation_style IN ('curious', 'upbeat', 'thoughtful', 'concise')),
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  disabled_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.automated_audience_balances (
  user_id uuid PRIMARY KEY REFERENCES public.automated_audience_accounts(user_id) ON DELETE RESTRICT,
  balance bigint NOT NULL DEFAULT 0 CHECK (balance >= 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.automated_audience_ledger (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.automated_audience_accounts(user_id) ON DELETE RESTRICT,
  amount bigint NOT NULL CHECK (amount <> 0),
  entry_type text NOT NULL CHECK (entry_type IN ('initial_allocation', 'gift_spend')),
  stream_id uuid REFERENCES public.streams(id) ON DELETE SET NULL,
  event_id uuid,
  idempotency_key text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.automated_audience_settings (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  enabled boolean NOT NULL DEFAULT false,
  chat_min_interval_minutes integer NOT NULL DEFAULT 5
    CHECK (chat_min_interval_minutes BETWEEN 3 AND 30),
  chat_max_interval_minutes integer NOT NULL DEFAULT 12
    CHECK (chat_max_interval_minutes BETWEEN 3 AND 60),
  gift_cooldown_minutes integer NOT NULL DEFAULT 20
    CHECK (gift_cooldown_minutes BETWEEN 15 AND 240),
  updated_by uuid REFERENCES public.user_profiles(id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (chat_max_interval_minutes >= chat_min_interval_minutes)
);

INSERT INTO public.automated_audience_settings (singleton)
VALUES (true)
ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.automated_audience_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  stream_id uuid NOT NULL UNIQUE REFERENCES public.streams(id) ON DELETE CASCADE,
  admin_user_id uuid NOT NULL REFERENCES public.user_profiles(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'paused', 'stopped', 'ended')),
  next_action_at timestamptz NOT NULL DEFAULT now(),
  last_action_at timestamptz,
  last_gift_at timestamptz,
  action_sequence bigint NOT NULL DEFAULT 0,
  started_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS automated_audience_sessions_due_idx
  ON public.automated_audience_sessions (next_action_at)
  WHERE status = 'active';

CREATE TABLE IF NOT EXISTS public.automated_audience_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id uuid NOT NULL REFERENCES public.automated_audience_sessions(id) ON DELETE CASCADE,
  stream_id uuid NOT NULL REFERENCES public.streams(id) ON DELETE CASCADE,
  account_id uuid NOT NULL REFERENCES public.automated_audience_accounts(user_id) ON DELETE RESTRICT,
  event_type text NOT NULL CHECK (event_type IN ('chat', 'gift')),
  content text,
  gift_id text,
  gift_name text,
  gift_icon text,
  internal_cost bigint NOT NULL DEFAULT 0 CHECK (internal_cost >= 0),
  idempotency_key text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (event_type = 'chat' AND content IS NOT NULL AND gift_id IS NULL)
    OR (event_type = 'gift' AND gift_id IS NOT NULL AND content IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS automated_audience_events_stream_created_idx
  ON public.automated_audience_events (stream_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.automated_audience_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id uuid REFERENCES public.automated_audience_sessions(id) ON DELETE SET NULL,
  stream_id uuid REFERENCES public.streams(id) ON DELETE SET NULL,
  actor_id uuid REFERENCES public.user_profiles(id) ON DELETE SET NULL,
  event_type text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS automated_audience_logs_created_idx
  ON public.automated_audience_logs (created_at DESC);

