CREATE OR REPLACE FUNCTION public.automated_audience_register_account(
  p_user_id uuid,
  p_account_key text,
  p_conversation_style text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_ledger_id uuid;
BEGIN
  IF p_user_id IS NULL
     OR p_account_key IS NULL
     OR length(trim(p_account_key)) = 0
     OR p_conversation_style IS NULL
     OR p_conversation_style NOT IN ('curious', 'upbeat', 'thoughtful', 'concise') THEN
    RAISE EXCEPTION 'Invalid automated audience account';
  END IF;

  INSERT INTO public.automated_audience_accounts (user_id, account_key, conversation_style)
  VALUES (p_user_id, p_account_key, p_conversation_style)
  ON CONFLICT (user_id) DO NOTHING;

  IF NOT EXISTS (
    SELECT 1
    FROM public.automated_audience_accounts
    WHERE user_id = p_user_id
      AND account_key = p_account_key
      AND conversation_style = p_conversation_style
  ) THEN
    RAISE EXCEPTION 'Account ID is already registered under another key';
  END IF;

  INSERT INTO public.automated_audience_balances (user_id, balance)
  VALUES (p_user_id, 0)
  ON CONFLICT (user_id) DO NOTHING;

  INSERT INTO public.automated_audience_ledger (
    user_id, amount, entry_type, idempotency_key
  )
  VALUES (
    p_user_id, 100000, 'initial_allocation', 'initial-allocation:' || p_account_key
  )
  ON CONFLICT (idempotency_key) DO NOTHING
  RETURNING id INTO v_ledger_id;

  IF v_ledger_id IS NOT NULL THEN
    UPDATE public.automated_audience_balances
    SET balance = balance + 100000, updated_at = now()
    WHERE user_id = p_user_id;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.automated_audience_activate(
  p_stream_id uuid,
  p_admin_user_id uuid
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_stream jsonb;
  v_owner_id text;
  v_session_id uuid;
BEGIN
  SELECT to_jsonb(s) INTO v_stream
  FROM public.streams s
  WHERE s.id = p_stream_id;

  IF v_stream IS NULL THEN
    RAISE EXCEPTION 'Broadcast not found';
  END IF;

  v_owner_id := COALESCE(v_stream->>'broadcaster_id', v_stream->>'user_id');
  IF v_owner_id IS DISTINCT FROM p_admin_user_id::text THEN
    RAISE EXCEPTION 'Broadcast is not owned by the designated administrator';
  END IF;

  IF lower(COALESCE(v_stream->>'status', '')) <> 'live'
     OR lower(COALESCE(v_stream->>'is_live', 'false')) <> 'true' THEN
    RAISE EXCEPTION 'Broadcast is not active';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.automated_audience_settings
    WHERE singleton AND enabled
  ) THEN
    RAISE EXCEPTION 'Automated audience service is disabled';
  END IF;

  INSERT INTO public.automated_audience_sessions (stream_id, admin_user_id)
  VALUES (p_stream_id, p_admin_user_id)
  ON CONFLICT (stream_id) DO UPDATE
  SET status = CASE
        WHEN public.automated_audience_sessions.status IN ('stopped', 'ended')
          THEN public.automated_audience_sessions.status
        ELSE 'active'
      END,
      updated_at = now()
  RETURNING id INTO v_session_id;

  INSERT INTO public.automated_audience_logs (session_id, stream_id, actor_id, event_type)
  VALUES (v_session_id, p_stream_id, p_admin_user_id, 'activation_requested');

  RETURN v_session_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.automated_audience_set_settings(
  p_admin_user_id uuid,
  p_enabled boolean,
  p_chat_min_interval_minutes integer,
  p_chat_max_interval_minutes integer,
  p_gift_cooldown_minutes integer
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_chat_min_interval_minutes NOT BETWEEN 3 AND 30
     OR p_chat_max_interval_minutes NOT BETWEEN 3 AND 60
     OR p_chat_max_interval_minutes < p_chat_min_interval_minutes
     OR p_gift_cooldown_minutes NOT BETWEEN 15 AND 240 THEN
    RAISE EXCEPTION 'Audience frequency is outside the allowed safety limits';
  END IF;

  INSERT INTO public.automated_audience_settings (
    singleton, enabled, chat_min_interval_minutes, chat_max_interval_minutes,
    gift_cooldown_minutes, updated_by, updated_at
  )
  VALUES (
    true, p_enabled, p_chat_min_interval_minutes, p_chat_max_interval_minutes,
    p_gift_cooldown_minutes, p_admin_user_id, now()
  )
  ON CONFLICT (singleton) DO UPDATE
  SET enabled = EXCLUDED.enabled,
      chat_min_interval_minutes = EXCLUDED.chat_min_interval_minutes,
      chat_max_interval_minutes = EXCLUDED.chat_max_interval_minutes,
      gift_cooldown_minutes = EXCLUDED.gift_cooldown_minutes,
      updated_by = EXCLUDED.updated_by,
      updated_at = now();

  INSERT INTO public.automated_audience_logs (actor_id, event_type, details)
  VALUES (
    p_admin_user_id, 'settings_updated',
    jsonb_build_object(
      'enabled', p_enabled,
      'chat_min_interval_minutes', p_chat_min_interval_minutes,
      'chat_max_interval_minutes', p_chat_max_interval_minutes,
      'gift_cooldown_minutes', p_gift_cooldown_minutes
    )
  );

  IF NOT p_enabled THEN
    UPDATE public.automated_audience_sessions
    SET status = 'paused', updated_at = now()
    WHERE status = 'active';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.automated_audience_set_account_enabled(
  p_admin_user_id uuid,
  p_account_id uuid,
  p_enabled boolean
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE public.automated_audience_accounts
  SET enabled = p_enabled,
      disabled_at = CASE WHEN p_enabled THEN NULL ELSE now() END
  WHERE user_id = p_account_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Automated audience account not found';
  END IF;

  INSERT INTO public.automated_audience_logs (actor_id, event_type, details)
  VALUES (
    p_admin_user_id,
    CASE WHEN p_enabled THEN 'account_enabled' ELSE 'account_disabled' END,
    jsonb_build_object('account_id', p_account_id)
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.automated_audience_set_session_status(
  p_admin_user_id uuid,
  p_stream_id uuid,
  p_status text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_stream jsonb;
BEGIN
  IF p_status NOT IN ('active', 'paused', 'stopped') THEN
    RAISE EXCEPTION 'Invalid audience session status';
  END IF;

  SELECT to_jsonb(s) INTO v_stream
  FROM public.streams s
  WHERE s.id = p_stream_id;

  IF v_stream IS NULL
     OR COALESCE(v_stream->>'broadcaster_id', v_stream->>'user_id')
        IS DISTINCT FROM p_admin_user_id::text THEN
    RAISE EXCEPTION 'Broadcast is not owned by the designated administrator';
  END IF;

  IF p_status = 'active'
     AND (lower(COALESCE(v_stream->>'status', '')) <> 'live'
       OR lower(COALESCE(v_stream->>'is_live', 'false')) <> 'true') THEN
    RAISE EXCEPTION 'Cannot resume audience activity for an inactive broadcast';
  END IF;

  IF p_status = 'active'
     AND NOT EXISTS (
       SELECT 1 FROM public.automated_audience_settings
       WHERE singleton AND enabled
     ) THEN
    RAISE EXCEPTION 'Enable the audience service before resuming a session';
  END IF;

  UPDATE public.automated_audience_sessions
  SET status = p_status,
      ended_at = CASE WHEN p_status = 'stopped' THEN now() ELSE ended_at END,
      updated_at = now()
  WHERE stream_id = p_stream_id
    AND admin_user_id = p_admin_user_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Audience session not found';
  END IF;

  INSERT INTO public.automated_audience_logs (stream_id, actor_id, event_type)
  VALUES (p_stream_id, p_admin_user_id, 'session_' || p_status);
END;
$$;

CREATE OR REPLACE FUNCTION public.automated_audience_stop_on_broadcast_end()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_status text := lower(COALESCE(to_jsonb(NEW)->>'status', ''));
  v_live text := lower(COALESCE(to_jsonb(NEW)->>'is_live', 'false'));
BEGIN
  IF v_status = 'ended' OR v_live = 'false' THEN
    UPDATE public.automated_audience_sessions
    SET status = 'ended', ended_at = COALESCE(ended_at, now()), updated_at = now()
    WHERE stream_id = NEW.id AND status IN ('active', 'paused');

    IF FOUND THEN
      INSERT INTO public.automated_audience_logs (stream_id, event_type)
      VALUES (NEW.id, 'broadcast_ended');
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS automated_audience_stop_on_broadcast_end
  ON public.streams;
CREATE TRIGGER automated_audience_stop_on_broadcast_end
AFTER UPDATE OF status, is_live ON public.streams
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM NEW.status OR OLD.is_live IS DISTINCT FROM NEW.is_live)
EXECUTE FUNCTION public.automated_audience_stop_on_broadcast_end();

CREATE OR REPLACE FUNCTION public.automated_audience_tick()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_session record;
  v_account record;
  v_gift record;
  v_owner_id uuid;
  v_owner_name text;
  v_category text;
  v_title text;
  v_content text;
  v_event_id uuid;
  v_sequence bigint;
  v_min_interval integer;
  v_max_interval integer;
  v_gift_cooldown integer;
  v_interval integer;
  v_stream_state jsonb;
  v_action_type text;
  v_chat_template integer;
  v_username text;
  v_display_name text;
  v_timestamp text;
  v_conversation_style text;
  v_delivery_ok boolean;
BEGIN
  SELECT chat_min_interval_minutes, chat_max_interval_minutes, gift_cooldown_minutes
  INTO v_min_interval, v_max_interval, v_gift_cooldown
  FROM public.automated_audience_settings
  WHERE singleton AND enabled;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  FOR v_session IN
    SELECT s.id, s.stream_id, s.next_action_at, s.last_gift_at
    FROM public.automated_audience_sessions s
    WHERE s.status = 'active'
      AND s.next_action_at <= now()
    ORDER BY s.next_action_at
    LIMIT 1
    FOR UPDATE SKIP LOCKED
  LOOP
    SELECT to_jsonb(st) INTO v_stream_state
    FROM public.streams st
    WHERE st.id = v_session.stream_id;

    IF v_stream_state IS NULL
       OR lower(COALESCE(v_stream_state->>'status', '')) <> 'live'
       OR lower(COALESCE(v_stream_state->>'is_live', 'false')) <> 'true' THEN
      UPDATE public.automated_audience_sessions
      SET status = 'ended', ended_at = now(), updated_at = now()
      WHERE id = v_session.id;
      INSERT INTO public.automated_audience_logs (session_id, stream_id, event_type)
      VALUES (v_session.id, v_session.stream_id, 'inactive_broadcast_detected');
      CONTINUE;
    END IF;

    v_owner_id := COALESCE(v_stream_state->>'broadcaster_id', v_stream_state->>'user_id')::uuid;
    SELECT p.username INTO v_owner_name
    FROM public.user_profiles p
    WHERE p.id = v_owner_id;
    v_owner_name := COALESCE(NULLIF(v_owner_name, ''), 'Broadcaster');

    v_category := LEFT(COALESCE(v_stream_state->>'category', 'live broadcast'), 60);
    v_title := LEFT(COALESCE(NULLIF(v_stream_state->>'title', ''), v_category), 100);
    v_interval := v_min_interval + floor(random() * (v_max_interval - v_min_interval + 1))::integer;

    SELECT a.user_id, a.conversation_style, p.username, p.avatar_url, b.balance
    INTO v_account
    FROM public.automated_audience_accounts a
    JOIN public.user_profiles p ON p.id = a.user_id
    JOIN public.automated_audience_balances b ON b.user_id = a.user_id
    WHERE a.enabled
    ORDER BY random()
    LIMIT 1;

    IF NOT FOUND THEN
      UPDATE public.automated_audience_sessions
      SET next_action_at = now() + make_interval(mins => v_interval), updated_at = now()
      WHERE id = v_session.id;
      INSERT INTO public.automated_audience_logs (session_id, stream_id, event_type)
      VALUES (v_session.id, v_session.stream_id, 'no_enabled_accounts');
      CONTINUE;
    END IF;

    v_username := COALESCE(NULLIF(v_account.username, ''), 'MaiTroll Audience');
    v_display_name := v_username;
    v_timestamp := clock_timestamp()::text;

    IF random() < 0.12
       AND (v_session.last_gift_at IS NULL
         OR v_session.last_gift_at <= now() - make_interval(mins => v_gift_cooldown)) THEN
      SELECT
        gi.id::text AS id,
        gi.name,
        gi.icon,
        COALESCE(gi.coin_cost, gi.value, 0)::bigint AS cost
      INTO v_gift
      FROM public.gift_items gi
      WHERE gi.status = 'active'
        AND COALESCE(gi.coin_cost, gi.value, 0) > 0
        AND COALESCE(gi.coin_cost, gi.value, 0) <= v_account.balance
      ORDER BY random()
      LIMIT 1;

      IF FOUND THEN
        v_action_type := 'gift';
      ELSE
        v_action_type := 'chat';
      END IF;
    ELSE
      v_action_type := 'chat';
    END IF;

    UPDATE public.automated_audience_sessions
    SET action_sequence = action_sequence + 1,
        last_action_at = now(),
        next_action_at = now() + make_interval(mins => v_interval),
        last_gift_at = CASE WHEN v_action_type = 'gift' THEN now() ELSE last_gift_at END,
        updated_at = now()
    WHERE id = v_session.id
    RETURNING action_sequence INTO v_sequence;

    v_delivery_ok := true;
    IF v_action_type = 'gift' THEN
      UPDATE public.automated_audience_balances
      SET balance = balance - v_gift.cost, updated_at = now()
      WHERE user_id = v_account.user_id AND balance >= v_gift.cost;

      IF NOT FOUND THEN
        INSERT INTO public.automated_audience_logs (
          session_id, stream_id, event_type, details
        )
        VALUES (
          v_session.id, v_session.stream_id, 'gift_balance_race',
          jsonb_build_object('account_id', v_account.user_id, 'gift_id', v_gift.id)
        );
        CONTINUE;
      END IF;

      v_event_id := gen_random_uuid();
      INSERT INTO public.automated_audience_events (
        id, session_id, stream_id, account_id, event_type, gift_id,
        gift_name, gift_icon, internal_cost, idempotency_key
      )
      VALUES (
        v_event_id, v_session.id, v_session.stream_id, v_account.user_id,
        'gift', v_gift.id, v_gift.name, v_gift.icon, v_gift.cost,
        v_session.id::text || ':' || v_sequence::text
      );

      INSERT INTO public.automated_audience_ledger (
        user_id, amount, entry_type, stream_id, event_id, idempotency_key
      )
      VALUES (
        v_account.user_id, -v_gift.cost, 'gift_spend', v_session.stream_id,
        v_event_id, 'gift-spend:' || v_event_id::text
      );

      BEGIN
      PERFORM realtime.send(
        jsonb_build_object(
          'v', 1,
          'stream_id', v_session.stream_id,
          'txn_id', v_event_id,
          'ts', v_timestamp,
          's', v_account.user_id,
          'd', jsonb_build_object(
            'id', v_event_id,
            'gift_id', v_gift.id,
            'gift_name', v_gift.name,
            'gift_icon', COALESCE(v_gift.icon, '🎁'),
            'sender_id', v_account.user_id,
            'sender_name', v_display_name,
            'receiver_id', v_owner_id,
            'receiver_name', v_owner_name,
            'amount', v_gift.cost,
            'quantity', 1,
            'created_at', v_timestamp,
            'metadata', jsonb_build_object(
              'platform_controlled', true,
              'non_payable', true,
              'internal_cost', v_gift.cost
            )
          )
        ),
        'gift_sent',
        'broadcast-stream-' || v_session.stream_id::text,
        false
      );

      PERFORM realtime.send(
        jsonb_build_object(
          'stream_id', v_session.stream_id,
          'id', v_event_id,
          'gift_id', v_gift.id,
          'gift_name', v_gift.name,
          'gift_icon', COALESCE(v_gift.icon, '🎁'),
          'sender_id', v_account.user_id,
          'sender_user_id', v_account.user_id,
          'sender_name', v_display_name,
          'receiver_id', v_owner_id,
          'receiver_name', v_owner_name,
          'recipient_id', v_owner_id,
          'recipient_user_id', v_owner_id,
          'recipient_type', 'broadcaster',
          'amount', v_gift.cost,
          'quantity', 1,
          'created_at', v_timestamp,
          'metadata', jsonb_build_object(
            'platform_controlled', true,
            'non_payable', true,
            'internal_cost', v_gift.cost
          )
        ),
        'gift_sent',
        'stream-realtime:' || v_session.stream_id::text,
        false
      );
      EXCEPTION WHEN OTHERS THEN
        v_delivery_ok := false;
        INSERT INTO public.automated_audience_logs (
          session_id, stream_id, actor_id, event_type, details
        )
        VALUES (
          v_session.id, v_session.stream_id, v_account.user_id,
          'realtime_delivery_failed',
          jsonb_build_object(
            'event_id', v_event_id,
            'action_type', 'gift',
            'error', SQLERRM,
            'sqlstate', SQLSTATE
          )
        );
      END;
    ELSE
      v_chat_template := 1 + floor(random() * 8)::integer;
      v_conversation_style := v_account.conversation_style;
      v_content := CASE v_conversation_style
        WHEN 'curious' THEN CASE v_chat_template
          WHEN 1 THEN 'What part of ' || v_title || ' are you enjoying most?'
          WHEN 2 THEN 'How did you get started with ' || v_category || '?'
          WHEN 3 THEN 'Could you show a little more of ' || v_title || '?'
          ELSE 'What would you recommend for someone new to ' || v_category || '?'
        END
        WHEN 'upbeat' THEN CASE v_chat_template
          WHEN 1 THEN 'This ' || v_category || ' setup looks great!'
          WHEN 2 THEN 'Great to see ' || v_title || ' live!'
          WHEN 3 THEN 'That was a fun ' || v_category || ' moment!'
          ELSE 'Nice stream—keep it going!'
        END
        WHEN 'thoughtful' THEN CASE v_chat_template
          WHEN 1 THEN 'The pacing of this ' || v_category || ' broadcast works well.'
          WHEN 2 THEN 'The details in ' || v_title || ' are interesting.'
          WHEN 3 THEN 'That was a thoughtful way to approach it.'
          ELSE 'This is a nice change of pace for a live stream.'
        END
        ELSE CASE v_chat_template
          WHEN 1 THEN 'Nice ' || v_category || ' stream.'
          WHEN 2 THEN 'Good setup.'
          WHEN 3 THEN 'That was fun.'
          ELSE 'What is next?'
        END
      END;

      v_content := LEFT(v_content, 500);
      v_event_id := gen_random_uuid();
      INSERT INTO public.automated_audience_events (
        id, session_id, stream_id, account_id, event_type, content, idempotency_key
      )
      VALUES (
        v_event_id, v_session.id, v_session.stream_id, v_account.user_id,
        'chat', v_content, v_session.id::text || ':' || v_sequence::text
      );

      BEGIN
      PERFORM realtime.send(
        jsonb_build_object(
          'v', 1,
          't', 'chat',
          'stream_id', v_session.stream_id,
          'txn_id', v_event_id,
          'ts', v_timestamp,
          's', v_account.user_id,
          'd', jsonb_build_object(
            'content', v_content,
            'user_name', v_display_name,
            'user_avatar', v_account.avatar_url,
            'user_role', 'platform_controlled',
            'platform_controlled', true
          )
        ),
        'message',
        'broadcast-stream-' || v_session.stream_id::text,
        false
      );

      PERFORM realtime.send(
        jsonb_build_object(
          'id', v_event_id,
          'username', v_display_name,
          'content', v_content,
          'createdAt', (extract(epoch FROM now()) * 1000)::bigint,
          'avatarUrl', v_account.avatar_url,
          'is_platform_controlled', true
        ),
        'floating_chat',
        'floating-chat:' || v_session.stream_id::text,
        false
      );

      PERFORM realtime.send(
        jsonb_build_object(
          'id', v_event_id,
          'username', v_display_name,
          'content', v_content,
          'createdAt', (extract(epoch FROM now()) * 1000)::bigint,
          'avatarUrl', v_account.avatar_url,
          'is_platform_controlled', true
        ),
        'floating_chat',
        'stream-realtime:' || v_session.stream_id::text,
        false
      );
      EXCEPTION WHEN OTHERS THEN
        v_delivery_ok := false;
        INSERT INTO public.automated_audience_logs (
          session_id, stream_id, actor_id, event_type, details
        )
        VALUES (
          v_session.id, v_session.stream_id, v_account.user_id,
          'realtime_delivery_failed',
          jsonb_build_object(
            'event_id', v_event_id,
            'action_type', 'chat',
            'error', SQLERRM,
            'sqlstate', SQLSTATE
          )
        );
      END;
    END IF;

    INSERT INTO public.automated_audience_logs (
      session_id, stream_id, actor_id, event_type, details
    )
    VALUES (
      v_session.id, v_session.stream_id, v_account.user_id,
      CASE WHEN v_delivery_ok THEN 'action_dispatched' ELSE 'action_delivery_failed' END,
      jsonb_build_object('event_id', v_event_id, 'action_type', v_action_type)
    );
  END LOOP;
EXCEPTION WHEN OTHERS THEN
  INSERT INTO public.automated_audience_logs (event_type, details)
  VALUES (
    'scheduler_error',
    jsonb_build_object('error', SQLERRM, 'sqlstate', SQLSTATE)
  );
END;
$$;

